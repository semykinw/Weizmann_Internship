import numpy as np
import matplotlib.pyplot as plt

def draw_ellipse(azimuth_deg, ellipticity_deg, color, title):
    azimuth = np.radians(azimuth_deg)
    chi = np.radians(ellipticity_deg)

    a = 1.0
    b = np.tan(abs(chi))

    t = np.linspace(0, 2 * np.pi, 1000)
    x_ellipse = a * np.cos(t)
    y_ellipse = b * np.sin(t)

    x_rot = x_ellipse * np.cos(azimuth) - y_ellipse * np.sin(azimuth)
    y_rot = x_ellipse * np.sin(azimuth) + y_ellipse * np.cos(azimuth)

    x_circle = np.cos(t)
    y_circle = np.sin(t)

    fig, ax = plt.subplots(figsize=(6, 6))
    ax.plot(x_circle, y_circle, 'k-', linewidth=1.5, label='Unit circle')
    ax.plot(x_rot, y_rot, color=color, linewidth=2,
            label=f'ψ={azimuth_deg}°, χ={ellipticity_deg}°')
    ax.plot([-np.cos(azimuth), np.cos(azimuth)],
            [-np.sin(azimuth), np.sin(azimuth)],
            color=color, linestyle='--', linewidth=1, alpha=0.5)

    ax.set_aspect('equal')
    ax.grid(True, alpha=0.3)
    ax.legend(loc='upper center', bbox_to_anchor=(0.5, -0.1), ncol=1)
    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    ax.set_title(title)
    plt.tight_layout()
    plt.show()

draw_ellipse(azimuth_deg=-82.507, ellipticity_deg=-1.99,
             color='blue', title='Laser 445')

