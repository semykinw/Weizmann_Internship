import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

df = pd.read_csv("650_stability_3.csv", skiprows=7, header=None, sep=';')
time_raw = df.iloc[:, 1].astype(str).str.strip().values
power    = df.iloc[:, 2].astype(float).values

threshold = 0.01
peaks = []
i = 0
while i < len(power):
    if power[i] > threshold:
        j = i
        while j < len(power) and power[j] > threshold:
            j += 1
        max_val = np.max(power[i:j])
        max_idx = i + np.argmax(power[i:j])
        peaks.append((max_idx, max_val))
        i = j
    else:
        i += 1

print(f"Найдено пиков: {len(peaks)}")

peak_times = [time_raw[idx] for idx, val in peaks]
peak_vals  = [val for idx, val in peaks]

fig, ax = plt.subplots(figsize=(12, 5))

ax.scatter(range(len(peak_times)), peak_vals, color='red', s=50, zorder=5)
ax.set_xticks(range(len(peak_times)))
ax.set_xticklabels(peak_times, rotation=45, ha='right', fontsize=9)

y_min = min(peak_vals) - 0.005
y_max = max(peak_vals) + 0.005
ax.set_ylim(y_min, y_max)
ax.yaxis.set_major_formatter(plt.FuncFormatter(lambda x, _: f"{x:.3f}"))
ax.yaxis.set_major_locator(plt.MultipleLocator(0.001))

ax.set_xlabel("Time")
ax.set_ylabel("Power (W)")
ax.set_title("Power values for 650 nm laser")
ax.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

