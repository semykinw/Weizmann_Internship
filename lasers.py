import numpy as np
import plotly.graph_objects as go
from PIL import Image #class from the library
from scipy.optimize import curve_fit
pixel_size_mm = 0.00345
img = Image.open('445 nm nd 7_3.tif')
data = np.array(img, dtype=float)
ny, nx = data.shape
x = np.arange(nx) * pixel_size_mm
y = np.arange(ny) * pixel_size_mm
X, Y = np.meshgrid(x, y)

# --- 2D Gaussian ---
def gaussian_2d(XY, amplitude, x0, y0, sigma_x, sigma_y, offset):
    X, Y = XY
    exponent = -((X - x0)**2 / (2 * sigma_x**2) + (Y - y0)**2 / (2 * sigma_y**2))
    return (offset + amplitude * np.exp(exponent)).ravel()

# Начальное приближение
x0_guess = x[np.argmax(np.max(data, axis=0))]
y0_guess = y[np.argmax(np.max(data, axis=1))]
p0 = [data.max(), x0_guess, y0_guess, 1.0, 1.0, data.min()]

popt, _ = curve_fit(gaussian_2d, (X, Y), data.ravel(), p0=p0)
amplitude, x0, y0, sigma_x, sigma_y, offset = popt

print(f"Амплитуда:  {amplitude:.2f}")
print(f"Центр X:    {x0:.4f} мм")
print(f"Центр Y:    {y0:.4f} мм")
print(f"Sigma X:    {abs(sigma_x):.4f} мм")
print(f"Sigma Y:    {abs(sigma_y):.4f} мм")

# --- 3D график фита ---
data_fit = gaussian_2d((X, Y), *popt).reshape(ny, nx)

fig = go.Figure()

fig.add_trace(go.Surface(z=data, x=x, y=y,
                         colorscale='hot', opacity=0.6, name='Данные'))
fig.add_trace(go.Surface(z=data_fit, x=x, y=y,
                         colorscale='blues', opacity=0.7, name='Gaussian fit'))

fig.update_layout(
    title="Профиль пучка + Gaussian fit",
    scene=dict(
        xaxis_title="X (мм)",
        yaxis_title="Y (мм)",
        zaxis_title="Интенсивность"
    )
)

fig.show()

